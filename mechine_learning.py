# Regresi uji asums Klasik
import numpy as np
import matplotlib.pyplot as plt

# Generate random data
np.random.seed(0)
tahun = np.arange(1, 11) # Variabel independen tahun
var1 = np.random.normal(0, 1, 10) # Variabel independen 1 (nilai random yang
var2 = np.random.normal(0, 1, 10) # Variabel independen 2 (nilai random yang
nilai_y = 2 * var1 + 3 * var2 + np.random.normal(0, 1, 10)

# Perform linear regression
X = np.column_stack((var1, var2)) # Matrix X dengan variabel independen
X = np.column_stack((np.ones(len(tahun)), X)) # Tambahkan kolom untuk inter
beta = np.linalg.inv(X.T @ X) @ X.T @ nilai_y # Hitung parameter beta (koefisien)

print("Koefisien Regresi:")
for i in range(len(beta)):
    print(f"Beta{i}: {beta[i]}")

# Plotting data dan regresi
fig, ax = plt.subplots()
ax.scatter(tahun, nilai_y, color='blue', label='Data')
ax.plot(tahun, X @ beta, color='red', label='Regresi')
ax.set_xlabel('Tahun')
ax.set_ylabel('Nilai Y')
ax.legend()
plt.show()

